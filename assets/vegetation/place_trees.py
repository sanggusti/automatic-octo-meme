"""T1 vegetation placement (#17): T0 fuel grid -> Gazebo include fragment.

Reads a scenario's fuel (fuel_default + fuel_map over the grid), places one
tree instance per fuel cell above threshold (seeded pine/oak split), and
emits (1) an SDF world fragment of <include> tags with poses, (2) a sidecar
JSON mapping instance name -> flammability (T1 plugins join on this; SDF
<include> admits no custom children, so tags live beside the SDF, not in it).

Bushes: procedural canopy spheres (--bushes) documented in the manifest.

Usage: python assets/vegetation/place_trees.py forest_fire --seed 1 --out /tmp/veg
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

CELL_M = 5.0


def load_fuel(scenario: str) -> tuple[dict, int, int]:
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    from dmb.scenarios import load_scenario  # noqa: PLC0415

    config = load_scenario(scenario)
    fire = (config.raw.get("dynamics", {}) or {}).get("fire", {})
    grid = config.grid
    return fire, int(grid.get("width", 10)), int(grid.get("height", 10))


def place(fire: dict, width: int, height: int, seed: int, threshold: float = 0.5):
    rng = random.Random(seed)
    fuel_map = {(c["x"], c["y"]): float(c["fuel"]) for c in fire.get("fuel_map", [])}
    default = float(fire.get("fuel_default", 0.0))
    instances = []
    for x in range(width):
        for y in range(height):
            fuel = fuel_map.get((x, y), default)
            if fuel < threshold:
                continue
            species = "pine-tree" if rng.random() < 0.6 else "oak-tree"
            instances.append(
                {
                    "name": f"{species.replace('-', '_')}_x{x}_y{y}",
                    "species": species,
                    "x": x,
                    "y": y,
                    "flammability": round(fuel, 3),
                }
            )
    return instances


def to_sdf(instances: list[dict]) -> str:
    lines = ['<sdf version="1.9">', "  <!-- generated by place_trees.py -->"]
    for inst in instances:
        model = "Pine Tree" if inst["species"] == "pine-tree" else "Oak tree"
        lines.append("  <include>")
        lines.append(f"    <name>{inst['name']}</name>")
        lines.append(f"    <uri>model://{model}</uri>")
        lines.append(
            f"    <pose>{inst['x'] * CELL_M} {inst['y'] * CELL_M} 0 0 0 0</pose>"
        )
        lines.append("  </include>")
    lines.append("</sdf>")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Place T1 vegetation from T0 fuel.")
    parser.add_argument("scenario")
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--threshold", type=float, default=0.5)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    fire, width, height = load_fuel(args.scenario)
    instances = place(fire, width, height, args.seed, args.threshold)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "vegetation.sdf").write_text(to_sdf(instances))
    (out / "fuel_tags.json").write_text(
        json.dumps({i["name"]: i["flammability"] for i in instances}, indent=2)
    )
    print(f"{len(instances)} instances -> {out}")


if __name__ == "__main__":
    main()
